using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace VSA.Analyzers;

// Writes the context type of a module, for example NotesDbContext, into <Module>.Infrastructure.
// It lists every aggregate of <Module>.Domain, so the context maps them by convention.
[Generator]
public sealed class ModuleDbContextGenerator : IIncrementalGenerator {
    const string Suffix = ".Infrastructure";

    public void Initialize(IncrementalGeneratorInitializationContext context) {
        var model = context.CompilationProvider.Select((compilation, _) => Read(compilation));
        context.RegisterSourceOutput(model, (output, m) => {
            if (m is { } found) {
                output.AddSource($"{found.Module}DbContext.g.cs", Write(found.Module, found.Namespace, found.Aggregates));
            }
        });
    }

    static (string Module, string Namespace, string Aggregates)? Read(Compilation compilation) {
        var assembly = compilation.AssemblyName;
        if (assembly is null || !assembly.EndsWith(Suffix, System.StringComparison.Ordinal)
            || compilation.GetTypeByMetadataName("VSA.Infrastructure.EfCore.ModuleDbContext") is null
            || compilation.GetTypeByMetadataName("VSA.Domain.AggregateRoot`1") is not { } aggregateRoot) {
            return null;
        }
        var module = assembly.Substring(0, assembly.Length - Suffix.Length);
        var domain = compilation.SourceModule.ReferencedAssemblySymbols.FirstOrDefault(a => a.Name == module + ".Domain");
        var aggregates = domain is null
            ? new string[0]
            : Types(domain.GlobalNamespace)
                .Where(type => !type.IsAbstract && Inherits(type, aggregateRoot))
                .Select(type => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
                .OrderBy(name => name, System.StringComparer.Ordinal)
                .ToArray();
        return (module, assembly, string.Join(",", aggregates));
    }

    static IEnumerable<INamedTypeSymbol> Types(INamespaceSymbol ns) {
        foreach (var type in ns.GetTypeMembers()) {
            yield return type;
        }
        foreach (var child in ns.GetNamespaceMembers()) {
            foreach (var type in Types(child)) {
                yield return type;
            }
        }
    }

    static bool Inherits(INamedTypeSymbol type, INamedTypeSymbol openBase) {
        for (var b = type.BaseType; b is not null; b = b.BaseType) {
            if (SymbolEqualityComparer.Default.Equals(b.OriginalDefinition, openBase)) {
                return true;
            }
        }
        return false;
    }

    static string Write(string module, string ns, string aggregates) {
        var types = aggregates.Length == 0 ? "" : string.Join(", ", aggregates.Split(',').Select(a => $"typeof({a})"));
        var name = module + "DbContext";
        var code = new StringBuilder();
        code.AppendLine("// <auto-generated/> by VSA.Analyzers: the context type of the " + module + " module.");
        code.AppendLine("#nullable enable");
        code.AppendLine($"namespace {ns};");
        code.AppendLine();
        code.AppendLine($"internal sealed partial class {name}(global::Microsoft.EntityFrameworkCore.DbContextOptions<{name}> options)");
        code.AppendLine("    : global::VSA.Infrastructure.EfCore.ModuleDbContext(options), global::VSA.Infrastructure.EfCore.IModuleDbContext {");
        code.AppendLine($"    public static global::System.Collections.Generic.IReadOnlyList<global::System.Type> AggregateTypes {{ get; }} = [{types}];");
        code.AppendLine();
        code.AppendLine("    protected override global::System.Collections.Generic.IReadOnlyList<global::System.Type> Aggregates => AggregateTypes;");
        code.AppendLine("}");
        return code.ToString();
    }
}
