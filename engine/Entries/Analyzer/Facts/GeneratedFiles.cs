namespace UmpireEngine;

using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;

static class GeneratedFiles {
    const string GeneratedOption = "generated_code";
    const string Marker = "<auto-generated";

    static readonly string[] Endings = [".designer.cs", ".generated.cs", ".g.cs", ".g.i.cs"];

    public static bool Is(SyntaxTree tree, AnalyzerOptions options, CancellationToken cancellation) {
        if (options.AnalyzerConfigOptionsProvider.GetOptions(tree).TryGetValue(GeneratedOption, out var value)) {
            return string.Equals(value, "true", StringComparison.OrdinalIgnoreCase);
        }
        var name = Path.GetFileName(tree.FilePath);
        if (name.StartsWith("TemporaryGeneratedFile_", StringComparison.OrdinalIgnoreCase)
            || Endings.Any(ending => name.EndsWith(ending, StringComparison.OrdinalIgnoreCase))) {
            return true;
        }
        return tree.GetRoot(cancellation).GetLeadingTrivia().Any(trivia => trivia.ToString().Contains(Marker));
    }
}
